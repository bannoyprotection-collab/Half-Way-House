export const createDefaultActivityDetails = (
  overrides?: Partial<Record<ActivityWorkItem['category'], Partial<ActivityWorkItem>>>
): ActivityWorkItem[] => {
  const categories: ActivityWorkItem['category'][] = [
    'agriculture',
    'livestock',
    'handicraft',
    'service',
    'wageLabor',
    'other',
  ];

  return categories.map((cat) => {
    const ov = overrides?.[cat] || {};
    return {
      category: cat,
      enabled: ov.enabled ?? false,
      details: ov.details ?? '',
      participationType: ov.participationType ?? 'occupational_therapy',
      occupationalTherapyIncome: ov.occupationalTherapyIncome ?? 0,
      employmentIncome: ov.employmentIncome ?? {
        commuteIncome: 0,
        homeWorkIncome: 0,
        section25Income: 0,
        section33Income: 0,
        section35Income: 0,
      },
      workplaceName: ov.workplaceName ?? '',
    };
  });
};

